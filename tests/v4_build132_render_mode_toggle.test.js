const fs = require('fs');
const path = require('path');
const root = path.resolve(__dirname, '..');
const html = fs.readFileSync(path.join(root, 'app/src/main/assets/index.html'), 'utf8');
const companions = fs.readFileSync(path.join(root, 'app/src/main/assets/js/companions.js'), 'utf8');
const mode = fs.readFileSync(path.join(root, 'app/src/main/assets/js/walk_render_mode_b133.js'), 'utf8');
const css = fs.readFileSync(path.join(root, 'app/src/main/assets/style.css'), 'utf8');
function ok(v, msg) { if (!v) throw new Error(msg); }
ok(companions.includes('WALK_RENDER_LEGACY_2D'), 'legacy 2D renderer is not captured before isometric load');
ok(!companions.includes('walkRenderModeToggle'), 'pre-walk setup must no longer contain the mode toggle');
ok(html.includes('id="walkRenderModeToggle"'), 'Options mode toggle is missing');
ok(html.indexOf('walkRenderModeToggle') > html.indexOf('id="saveSlots"'), 'mode toggle must live next to save slots in Options');
ok(mode.includes('luciole_walk_render_mode_test'), 'render mode persistence key missing');
ok(mode.includes('LEGACY_RESOURCE_ICONS'), 'legacy v3.2.7 resource icon mapping missing');
ok(mode.includes("graine.svg") && mode.includes("baie.svg") && mode.includes("ambre.svg"), 'legacy resource art mapping is incomplete');
ok(mode.includes("sheet.disabled = twoD"), '2D mode must disable the v4 commercial menu stylesheet');
ok(mode.includes('legacy-2d-ui'), 'legacy menu/HUD class dispatch missing');
ok(mode.includes('current() === MODE_2D'), '2D dispatch is missing');
ok(mode.includes('return 1;'), '2D movement must disable isometric speed compensation');
ok(mode.includes('return { x: x, y: y };'), '2D mode must bypass v4 obstacle projection/collision');
ok(css.includes('.walk-render-mode-option'), 'Options toggle styling missing');
ok(css.includes('.legacy-2d-expedition-ui'), 'legacy 2D expedition HUD styling missing');
const companionsPos = html.indexOf('js/companions.js');
const isoPos = html.indexOf('js/isometric_v4_b126.js');
const hudPos = html.indexOf('js/commercial_hud_v4_b120.js');
const modePos = html.indexOf('js/walk_render_mode_b133.js');
ok(companionsPos >= 0 && isoPos > companionsPos, 'companions must load before isometric renderer');
ok(modePos > hudPos && hudPos > isoPos, 'render mode dispatcher must load after final v4 wrappers');
console.log('v4_build133_render_mode_toggle: OK');
